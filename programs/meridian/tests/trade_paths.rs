/// Re-derives the book's expected escrow totals from its own live orders and asserts
/// they match the escrow token accounts' actual balances (private copy of
/// `tests/book.rs`'s `assert_escrow_invariants`).
fn assert_escrow_invariants(env: &Env, market: &CreateMarketResult) {
    let account = env.svm.get_account(&addr(market.book)).expect("book account should exist");
    let mut data = account.data.clone();
    let header = read_header(&data).expect("book header should validate");
    let capacity = header.capacity;

    let bid_total: u64 = {
        let bids = bids_mut(&mut data, capacity).expect("bids slice");
        bids[..header.bid_count as usize].iter().map(|o| o.price * o.remaining).sum()
    };
    let ask_total: u64 = {
        let asks = asks_mut(&mut data, capacity).expect("asks slice");
        asks[..header.ask_count as usize].iter().map(|o| o.remaining * 1_000_000).sum()
    };

    assert!(
        read_token_amount(env, market.usdc_escrow) >= bid_total,
        "usdc_escrow invariant violated: want >= {bid_total}, got {}",
        read_token_amount(env, market.usdc_escrow)
    );
    assert!(
        read_token_amount(env, market.yes_escrow) >= ask_total,
        "yes_escrow invariant violated: want >= {ask_total}, got {}",
        read_token_amount(env, market.yes_escrow)
    );
}

/// Asserts the vault holds at least `pairs_outstanding * 1_000_000` (the `Open`-market
/// invariant form).
fn assert_vault_invariant(env: &Env, market: &CreateMarketResult) {
    let m: Market = env.fetch(market.market);
    assert!(
        read_token_amount(env, market.vault) >= m.pairs_outstanding * ONE_USDC,
        "vault invariant violated"
    );
}

/// Seeds `count` makers each resting a `qty_each`-token bid at `price`, returning
/// their USDC token accounts (for `buy_no_market`'s `remaining_accounts`) in arrival
/// order.
fn seed_bids(env: &mut Env, market: &CreateMarketResult, count: usize, qty_each: u64, price: u64) -> Vec<Pubkey> {
    let mut makers_yes = Vec::new();
    for _ in 0..count {
        let (maker, maker_usdc) = funded_user(env, 10_000 * ONE_USDC);
        // `buy_no_market`'s Yes-leg transfer to a bid maker is a raw `token::transfer`
        // (not `init_if_needed`), so the maker's Yes ATA must already exist even
        // though a bid maker never minted/held any Yes themselves.
        let yes_mint_addr = addr(market.yes_mint);
        let maker_yes = pk(CreateAssociatedTokenAccount::new(&mut env.svm, &maker, &yes_mint_addr)
            .send()
            .expect("create maker Yes ata should succeed"));
        send_place_order(env, &maker, market, maker_usdc, maker_yes, SIDE_BID, price, qty_each, TIF_LIMIT, &[])
            .expect("maker bid should rest");
        makers_yes.push(maker_yes);
    }
    makers_yes
}

/// Seeds `count` makers each resting a `qty_each`-token ask at `price` (minting the
/// Yes they ask with first), returning their USDC token accounts (for
/// `sell_no_market`'s `remaining_accounts`) in arrival order.
fn seed_asks(env: &mut Env, market: &CreateMarketResult, count: usize, qty_each: u64, price: u64) -> Vec<Pubkey> {
    let mut makers_usdc = Vec::new();
    for _ in 0..count {
        let (maker, maker_usdc) = funded_user(env, 10_000 * ONE_USDC);
        mint_pairs_for(env, &maker, market, maker_usdc, qty_each);
        let maker_yes = yes_ata(&maker, market);
        send_place_order(env, &maker, market, maker_usdc, maker_yes, SIDE_ASK, price, qty_each, TIF_LIMIT, &[])
            .expect("maker ask should rest");
        makers_usdc.push(maker_usdc);
    }
    makers_usdc
}

