/// A fresh funded (SOL) user keypair.
fn new_user(env: &mut Env) -> Keypair {
    let user = Keypair::new();
    env.airdrop(user.pubkey_pk(), 10_000_000_000);
    user
}

/// Creates `user`'s USDC associated token account (payer = owner = `user`).
fn create_usdc_ata(env: &mut Env, user: &Keypair) -> Pubkey {
    let usdc_mint_addr = addr(env.usdc_mint);
    let ata = CreateAssociatedTokenAccount::new(&mut env.svm, user, &usdc_mint_addr)
        .send()
        .expect("create user USDC ata should succeed");
    pk(ata)
}

/// Mints `amount` test USDC into `destination`, signed by `admin`.
fn mint_usdc(env: &mut Env, destination: Pubkey, amount: u64) {
    let admin = env.admin.insecure_clone();
    let usdc_mint_addr = addr(env.usdc_mint);
    let dest_addr = addr(destination);
    TokenMintTo::new(&mut env.svm, &admin, &usdc_mint_addr, &dest_addr, amount)
        .send()
        .expect("mint test USDC should succeed");
}

/// Raw SPL token account `amount` field (bytes 64..72); plain SPL accounts have no
/// Anchor discriminator (private copy; see `tests/book.rs`'s `read_token_amount`).
fn read_token_amount(env: &Env, account: Pubkey) -> u64 {
    let acc = env
        .svm
        .get_account(&addr(account))
        .unwrap_or_else(|| panic!("token account {account} missing"));
    u64::from_le_bytes(acc.data[64..72].try_into().unwrap())
}

/// Raw SPL mint `supply` field (bytes 36..44; private copy, see `tests/create_market.rs`'s
/// `read_mint_supply`).
fn read_mint_supply(env: &Env, mint: Pubkey) -> u64 {
    let account = env.svm.get_account(&addr(mint)).expect("mint account missing");
    u64::from_le_bytes(account.data[36..44].try_into().unwrap())
}

/// Decodes a standard (RFC 4648, padded) base64 string into raw bytes. No base64 crate
/// is a direct dependency of this test crate, so this is a small private decoder --
/// just enough to read litesvm's `Program data: <base64>` log lines (T025 proof).
fn base64_decode(s: &str) -> Vec<u8> {
    const ALPHABET: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut reverse = [255u8; 256];
    for (i, &c) in ALPHABET.iter().enumerate() {
        reverse[c as usize] = i as u8;
    }

    let mut out = Vec::new();
    let mut buf: u32 = 0;
    let mut bits: u32 = 0;
    for &b in s.as_bytes() {
        if b == b'=' {
            break;
        }
        let v = reverse[b as usize];
        assert_ne!(v, 255, "invalid base64 character in log line: {}", b as char);
        buf = (buf << 6) | v as u32;
        bits += 6;
        if bits >= 8 {
            bits -= 8;
            out.push((buf >> bits) as u8);
        }
    }
    out
}

/// Scans `logs` for `Program data: <base64>` lines (litesvm's rendering of Anchor's
/// `emit!`, which calls the `sol_log_data` syscall), decodes each, and collects every
/// one whose leading 8-byte discriminator matches `Fill::DISCRIMINATOR` (Anchor's own
/// `sha256("event:Fill")[..8]`, generated by the `#[event]` macro) -- in log order,
/// which is emission order (T025 proof; private helper, no cross-file test helper
/// sharing).
fn decode_fill_events(logs: &[String]) -> Vec<Fill> {
    let mut out = Vec::new();
    for log in logs {
        let Some(b64) = log.strip_prefix("Program data: ") else {
            continue;
        };
        let bytes = base64_decode(b64);
        if bytes.len() < 8 || &bytes[..8] != Fill::DISCRIMINATOR {
            continue;
        }
        let mut slice = &bytes[8..];
        let fill = Fill::deserialize(&mut slice).expect("Fill event should borsh-decode");
        out.push(fill);
    }
    out
}

fn to_sdk_metas(metas: Vec<anchor_lang::prelude::AccountMeta>) -> Vec<SdkAccountMeta> {
    metas
        .into_iter()
        .map(|m| SdkAccountMeta {
            pubkey: addr(m.pubkey),
            is_signer: m.is_signer,
            is_writable: m.is_writable,
        })
        .collect()
}

/// A fresh user with `usdc_funding` test USDC already in their own ATA.
fn funded_user(env: &mut Env, usdc_funding: u64) -> (Keypair, Pubkey) {
    let user = new_user(env);
    let user_usdc = create_usdc_ata(env, &user);
    if usdc_funding > 0 {
        mint_usdc(env, user_usdc, usdc_funding);
    }
    (user, user_usdc)
}

