//! `buy_no_market` / `buy_no_limit` / `sell_no_market` tests (Wave 5, T049/T059 proof).
//!
//! Covers the three Buy-No/Sell-No trade paths from
//! `specs/001-binary-outcome-markets/research.md` R8: Buy No (market) mints `qty`
//! pairs, sells the Yes leg IOC into resting bids, and redeems the unfilled remainder
//! in the same instruction so the user ends holding only No (FR-013); Buy No (limit)
//! mints `qty` pairs and rests a Yes ask (FR-014's transient both-sides-held state);
//! Sell No (market) buys the Yes leg IOC from resting asks and redeems the filled
//! pairs. Also covers `InsufficientFill`, `BookFull`, `Paused`, `MarketSettled`, maker-
//! side balances, escrow/vault invariants, `Fill` events, and the 8-fill compute budget.

