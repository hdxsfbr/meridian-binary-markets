#[test]
fn sell_no_market_fill_events_decode_with_exact_fields_and_order() {
    let (mut env, market) = setup();

    // Give the seller a deep No position to sell from.
    let bid_makers = seed_bids(&mut env, &market, 1, 20, 500_000);
    let (seller, seller_usdc) = funded_user(&mut env, 10_000 * ONE_USDC);
    send_buy_no_market(&mut env, &seller, &market, seller_usdc, 20, 500_000, &bid_makers).expect("seed seller's No position");

    // Three resting asks at strictly ascending prices, so `match_against` fills them
    // in exactly this order (price-time priority) regardless of arrival.
    let mut makers = Vec::new(); // (wallet pubkey, USDC ATA)
    for (price, qty) in [(400_000u64, 2u64), (450_000, 3), (500_000, 1)] {
        let (maker, maker_usdc) = funded_user(&mut env, 10_000 * ONE_USDC);
        mint_pairs_for(&mut env, &maker, &market, maker_usdc, qty);
        let maker_yes = yes_ata(&maker, &market);
        send_place_order(&mut env, &maker, &market, maker_usdc, maker_yes, SIDE_ASK, price, qty, TIF_LIMIT, &[])
            .expect("maker ask should rest");
        makers.push((maker.pubkey_pk(), maker_usdc));
    }

    let remaining: Vec<Pubkey> = makers.iter().map(|(_, usdc)| *usdc).collect();
    let meta = send_sell_no_market(&mut env, &seller, &market, seller_usdc, 6, 500_000, &remaining)
        .expect("sell_no_market should fill all three resting levels");

    let fills = decode_fill_events(&meta.logs);
    assert_eq!(fills.len(), 3, "expected exactly 3 Fill events, got:\n{}", meta.logs.join("\n"));

    let expected = [
        (makers[0].0, 400_000u64, 2u64),
        (makers[1].0, 450_000u64, 3u64),
        (makers[2].0, 500_000u64, 1u64),
    ];
    let seller_pk = seller.pubkey_pk();
    for (fill, (maker_pk, price, qty)) in fills.iter().zip(expected.iter()) {
        assert_eq!(fill.market, market.market);
        assert_eq!(fill.maker, *maker_pk, "fills must appear in price-time priority order");
        assert_eq!(fill.taker, seller_pk);
        assert_eq!(fill.side_of_taker, SIDE_BID, "sell_no_market buys the Yes leg: the taker is the Bid side");
        assert_eq!(fill.price, *price);
        assert_eq!(fill.qty, *qty);
    }
}

