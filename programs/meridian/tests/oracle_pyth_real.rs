//! Layout and guard test on a synthetic `PriceUpdateV2` (Wave 6C, T089-T092; research.md R5).
//!
//! The Pyth API key is entitled to crypto feeds but not yet to `Equity.US` feeds (403
//! "Not entitled" -- see `services/automation/src/probe/pyth.ts` and the dated R5 note
//! in `specs/001-binary-outcome-markets/research.md`). This test exercises the
//! program's real-oracle parsing and settlement guards against the BTC/USD feed using
//! a SYNTHETIC `PriceUpdateV2` account: the fixture bytes in
//! `fixtures/pyth_price_update_btc.bin` were encoded by the real
//! `@pythnetwork/pyth-solana-receiver` SDK's own Anchor/Borsh coder from a real Hermes
//! BTC/USD response (see `fixtures/pyth_price_update_btc.json`'s sidecar), so the
//! price/conf/expo/publish_time/feed_id fields are real observed values -- but the
//! bytes were never posted to devnet by a transaction, and the receiver program's own
//! guardian-signature/VAA verification never ran against them. The
//! `verification_level: Full` byte in the encoding is simply the value the synthetic
//! encoder was told to write, not a cryptographic guarantee this test earned. See the
//! sidecar's `syntheticReason` and this crate's `research.md` R5 note: the devnet
//! airdrop needed to actually post it was rate-limited (daily limit reached), so the
//! fixture is clearly labelled `synthetic: true`.
//!
//! This is still a real test of this program's guard chain: `owner ==
//! config.oracle_program`, the `verification_level` field check, `feed_id` match, and
//! the four common guards in `oracle::read_quote` only look at the account's owner and
//! bytes, never at how it got there, so parsing these bytes through
//! `PriceUpdateV2::try_deserialize` and the full `settle_market` guard chain proves the
//! real on-chain *layout* parses through our guards -- the equity swap later is a
//! config value (`Config.tickers[].feed_id`), not a code change. It is NOT an
//! end-to-end proof that posting a real update and on-chain signature verification
//! succeed; that step was never exercised here (a future real `--post` run against a
//! funded devnet publisher, settling against the actually-posted account, would be
//! that proof).
//!
//! The fixture is regenerated by `probe pyth --post` against a *live* BTC/USD price
//! every time it runs (research.md R5's ticket price moves between runs, unlike the
//! other oracle tests' hand-built accounts), so nothing here hardcodes the captured
//! price/conf/publish_time/feed id: every expectation is derived by deserializing
//! `FIXTURE_BYTES` itself with the same `PriceUpdateV2::try_deserialize` and
//! `math::normalize_price` the program uses, and the strikes are chosen relative to
//! that derived price so the test stays correct run over run.

