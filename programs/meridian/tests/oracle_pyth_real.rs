/// Raw synthetic `PriceUpdateV2` account bytes built by `probe pyth --post`
/// (`services/automation/src/probe/pyth.ts`) when it falls back to the synthetic
/// path: an 8-byte Anchor discriminator followed by the Borsh-encoded struct, produced
/// by the real receiver SDK's own coder from a real Hermes BTC/USD response, but never
/// posted to devnet or signature-verified by the receiver program. See this file's
/// module doc comment and the sidecar JSON next to this fixture for why
/// `synthetic: true`.
const FIXTURE_BYTES: &[u8] = include_bytes!("fixtures/pyth_price_update_btc.bin");

/// Receiver program id (`fixtures/pyth_price_update_btc.json["owner"]`,
/// research.md R4/R5). Stable across probe runs, unlike the price fields.
const RECEIVER_PROGRAM_ID_STR: &str = "rec5EKMGg6MxZYaMdyBfgwp4d5rB9T1VQH5pJv5LtFJ";

const DAY: u32 = 20261007;
/// How far below/above the fixture's derived settlement price the two strike markets
/// sit ($1,000), comfortably clear of normal BTC intra-run price movement between
/// `probe pyth --post` runs.
const STRIKE_OFFSET_MICRO_USD: u64 = 1_000_000_000;

fn receiver_program_id() -> Pubkey {
    Pubkey::from_str(RECEIVER_PROGRAM_ID_STR).expect("receiver program id must parse")
}

/// Deserializes `FIXTURE_BYTES` with the same `PriceUpdateV2::try_deserialize` the
/// program's `oracle::pyth::parse` uses, so every test derives its expectations from
/// the fixture itself rather than a captured-at-write-time snapshot of its fields.
fn load_fixture() -> PriceUpdateV2 {
    let mut data: &[u8] = FIXTURE_BYTES;
    PriceUpdateV2::try_deserialize(&mut data).expect("fixture bytes should deserialize as PriceUpdateV2")
}

/// A `TickerInfo` ladder matching `default_tickers()` (`common::mod`), but with the
/// first entry replaced by a `BTC` ticker bound to the fixture's own feed id -- the
/// real Hermes BTC/USD feed, the crypto feed the current key *is* entitled to (module
/// doc comment).
fn tickers_with_btc(feed_id: [u8; 32]) -> Vec<TickerInfo> {
    let mut tickers = default_tickers();
    tickers[0] = TickerInfo {
        symbol: {
            let mut sym = [0u8; 8];
            sym[..3].copy_from_slice(b"BTC");
            sym
        },
        feed_id,
        enabled: true,
    };
    tickers
}

/// Initializes `Config` with `OracleProvider::PythReceiver`, `oracle_program` set to
/// the real receiver program id, and the BTC-swapped ticker ladder from
/// `tickers_with_btc`. No publishers are needed (`PythReceiver` doesn't use the mock
/// allowlist -- see `Config::validate`).
fn init_pyth_receiver_config(env: &mut Env, feed_id: [u8; 32]) {
    let args = InitializeConfigArgs {
        oracle_provider: OracleProvider::PythReceiver,
        oracle_program: receiver_program_id(),
        publishers: vec![],
        max_staleness_secs: 300,
        max_conf_bps: 25,
        min_publish_offset_secs: 60,
        override_delay_secs: 3600,
        tickers: tickers_with_btc(feed_id),
        default_book_capacity: 16,
    };
    env.init_config_with(args).expect("init_config with PythReceiver provider should succeed");
}

/// Plants `FIXTURE_BYTES` at a fresh address via `svm.set_account`, owned by the real
/// receiver program id. This is a layout/guard test fixture, not a replay of a real
/// devnet transaction: the account's owner and bytes are real-shaped, but nothing here
/// posted or signature-verified them on chain (module doc comment).
fn plant_fixture(env: &mut Env) -> Pubkey {
    let address = Pubkey::new_unique();
    let account = SvmAccount {
        lamports: 1_000_000_000,
        data: FIXTURE_BYTES.to_vec(),
        owner: addr(receiver_program_id()),
        executable: false,
        rent_epoch: 0,
    };
    env.svm.set_account(addr(address), account).expect("set_account should succeed");
    address
}

fn create_btc_market(env: &mut Env, strike: u64, close_ts: i64, trading_day: u32) -> Pubkey {
    env.create_market(CreateMarketArgs::new("BTC", strike, trading_day, close_ts, 16))
        .expect("create_market for BTC should succeed")
        .market
}

fn settle_market(env: &mut Env, market: Pubkey, price_account: Pubkey) -> litesvm::types::TransactionResult {
    let admin = env.admin.insecure_clone();
    let accounts = meridian::accounts::SettleMarket {
        caller: admin.pubkey_pk(),
        config: config_pda(),
        market,
        price_account,
    };
    let data = meridian::instruction::SettleMarket {};
    let ix = build_ix(meridian::ID, accounts, data);
    env.send(&[ix], &[&admin])
}

#[test]
fn synthetic_price_update_v2_layout_and_guard_settles_yes_when_price_above_strike() {
    let fixture = load_fixture();
    let settlement_price = normalize_price(fixture.price_message.price, fixture.price_message.exponent)
        .expect("fixture price should normalize");
    let strike = settlement_price - STRIKE_OFFSET_MICRO_USD;
    let publish_time = fixture.price_message.publish_time;

    let mut env = Env::new();
    init_pyth_receiver_config(&mut env, fixture.price_message.feed_id);

    let close_ts = publish_time - 30;
    let market = create_btc_market(&mut env, strike, close_ts, DAY);
    let price_account = plant_fixture(&mut env);

    env.warp_to(publish_time + 10);
    settle_market(&mut env, market, price_account)
        .expect("settle_market should succeed against the real PriceUpdateV2 layout");

    let m: Market = env.fetch(market);
    assert_eq!(m.state, MarketState::Settled);
    assert_eq!(m.outcome, Outcome::Yes);
    assert_eq!(m.settlement_price, settlement_price);
}

#[test]
fn synthetic_price_update_v2_layout_and_guard_settles_no_when_price_below_strike() {
    let fixture = load_fixture();
    let settlement_price = normalize_price(fixture.price_message.price, fixture.price_message.exponent)
        .expect("fixture price should normalize");
    let strike = settlement_price + STRIKE_OFFSET_MICRO_USD;
    let publish_time = fixture.price_message.publish_time;

    let mut env = Env::new();
    init_pyth_receiver_config(&mut env, fixture.price_message.feed_id);

    let close_ts = publish_time - 30;
    let market = create_btc_market(&mut env, strike, close_ts, DAY + 1);
    let price_account = plant_fixture(&mut env);

    env.warp_to(publish_time + 10);
    settle_market(&mut env, market, price_account)
        .expect("settle_market should succeed against the real PriceUpdateV2 layout");

    let m: Market = env.fetch(market);
    assert_eq!(m.state, MarketState::Settled);
    assert_eq!(m.outcome, Outcome::No);
    assert_eq!(m.settlement_price, settlement_price);
}

#[test]
fn synthetic_price_update_v2_layout_and_guard_is_stale_301s_after_publish_time() {
    let fixture = load_fixture();
    let settlement_price = normalize_price(fixture.price_message.price, fixture.price_message.exponent)
        .expect("fixture price should normalize");
    let strike = settlement_price - STRIKE_OFFSET_MICRO_USD;
    let publish_time = fixture.price_message.publish_time;

    let mut env = Env::new();
    init_pyth_receiver_config(&mut env, fixture.price_message.feed_id);

    // A fresh market (never touched by the other tests' settle calls) with the same
    // close_ts shape, so only the staleness window differs.
    let close_ts = publish_time - 30;
    let market = create_btc_market(&mut env, strike, close_ts, DAY + 2);
    let price_account = plant_fixture(&mut env);

    env.warp_to(publish_time + 301);
    let result = settle_market(&mut env, market, price_account);
    assert_err(&result, MeridianError::OracleStale);

    let m: Market = env.fetch(market);
    assert_eq!(m.state, MarketState::Open);
    assert_eq!(m.outcome, Outcome::Unset);
}
