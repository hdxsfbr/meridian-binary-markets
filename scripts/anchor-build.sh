#!/usr/bin/env bash
# Ensures a program keypair exists (never committed -- keys/ is gitignored),
# copies it to target/deploy so Anchor picks it up, syncs declare_id!/
# Anchor.toml to match it, then runs `anchor build`. Shared by `make build`,
# `make dev` and `make test-program` so the key-prep logic lives in one place.
set -euo pipefail

mkdir -p keys target/deploy

if [ ! -f keys/program-keypair.json ]; then
  solana-keygen new --no-bip39-passphrase --silent -o keys/program-keypair.json
fi

cp -f keys/program-keypair.json target/deploy/meridian-keypair.json
anchor keys sync

# `anchor keys sync` only rewrites the [programs.<active-cluster>] entry in
# Anchor.toml (plus declare_id! in lib.rs). Force both the localnet and
# devnet entries to match the same keypair so anchor-litesvm's
# fromWorkspace() (which reads every entry) never sees a stale id.
PROGRAM_ID="$(solana-keygen pubkey keys/program-keypair.json)"
sed -i -E "s/^meridian = \"[^\"]+\"/meridian = \"${PROGRAM_ID}\"/" Anchor.toml

# Keep the SDK's program id in sync with the keypair/Anchor.toml/declare_id!
# above, instead of hard-coding it in packages/sdk/src/index.ts.
cat > packages/sdk/src/program-id.ts <<EOF
// Generated by scripts/anchor-build.sh from the synced program keypair.
// Do not edit by hand -- it is overwritten on every build.
export const PROGRAM_ID_BASE58 = "${PROGRAM_ID}";
EOF

# --arch v1: anchor build defaults to v3 (newest SBPF ISA). Program tests moved to
# Rust on the `litesvm` crate 0.12.0 (DECISIONS.md §7, 2026-10-06), which is a newer
# litesvm generation than the retired TS harness's -- but its bundled verifier/loader
# still rejects a v3-arch .so with "InvalidAccountData" when loaded via
# `LiteSVM::add_program_from_file` (confirmed directly, not assumed). v1 is the oldest
# arch cargo-build-sbf exposes that litesvm 0.12.0 loads.
anchor build --arch v1

# Publish the generated IDL to the SDK as a TypeScript module so the web app,
# the automation service and scripts can build an Anchor client without
# reading target/ at runtime. Generated file, gitignored.
if [ -f target/idl/meridian.json ]; then
  {
    echo "// Generated by scripts/anchor-build.sh from target/idl/meridian.json."
    echo "// Do not edit by hand -- it is overwritten on every build."
    printf 'export const IDL = '
    cat target/idl/meridian.json
    echo " as const;"
  } > packages/sdk/src/idl.ts
fi
